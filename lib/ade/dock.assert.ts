import { dockAllowed, clampDock, defaultDock, dockKey, projectIdFromPath, DOCK_MIN } from "./dock"
let pass = 0, fail = 0
const eq = (m: string, a: unknown, b: unknown) => { JSON.stringify(a) === JSON.stringify(b) ? pass++ : (fail++, console.log("FAIL", m, JSON.stringify(a), JSON.stringify(b))) }
eq("shows on dashboard at desktop", dockAllowed("/dashboard", 1440), true)
eq("shows on a project", dockAllowed("/project/abc", 1440), true)
eq("never on the full chat", dockAllowed("/chat", 1440), false)
eq("never on a chat thread", dockAllowed("/chat/123", 1440), false)
eq("never on sign-in", dockAllowed("/sign-in", 1440), false)
eq("not under 1100", dockAllowed("/dashboard", 1099), false)
eq("/chatter is not /chat", dockAllowed("/chatter", 1440), true)
eq("default is 40%", defaultDock(2000), 800)
eq("default has a floor", defaultDock(1100), DOCK_MIN + 100)
eq("clamp low", clampDock(10, 1600), DOCK_MIN)
eq("clamp high", clampDock(5000, 1600), 1120)
eq("arrow left narrows", dockKey(800, "ArrowLeft", 2000), 760)
eq("arrow right widens", dockKey(800, "ArrowRight", 2000), 840)
eq("home", dockKey(800, "Home", 2000), DOCK_MIN)
eq("end", dockKey(800, "End", 2000), 1400)
eq("other keys ignored", dockKey(800, "a", 2000), null)
eq("project id", projectIdFromPath("/project/3f2504e0-4f89-11d3-9a0c-0305e82c3301/plan"), "3f2504e0-4f89-11d3-9a0c-0305e82c3301")
eq("not a project id", projectIdFromPath("/project/new"), null)
eq("projects list is not a project", projectIdFromPath("/projects"), null)
console.log(`dock.assert: ${pass} passed, ${fail} failed`)
process.exit(fail ? 1 : 0)
